"""Deploy containers only on the approved EC2 host with an active launch-time cutoff.

This command creates no AWS resources. Run as a module from the repository root.
Docker output is captured to avoid displaying interpolated private configuration.
"""

import argparse
import json
import os
import re
import shlex
import stat
import subprocess
from datetime import UTC, datetime
from pathlib import Path
from urllib.request import ProxyHandler, Request, build_opener

from deploy.aws.configure_env import validate_domain
from deploy.aws.shutdown_deadline import shutdown_deadline

ROOT = Path(__file__).resolve().parents[2]
PROTECTED_INSTANCE = "i-0b8d60a2621893ac1"  # mwalimulens-demo: never a deployment target.


def run_command(arguments: list[str], *, timeout: int = 60) -> str:
    result = subprocess.run(arguments, capture_output=True, text=True, timeout=timeout, check=False)
    if result.returncode:
        raise RuntimeError(f"Operation failed ({arguments[0]}); private output was withheld.")
    return result.stdout


def validate_environment(path: Path) -> None:
    if os.name == "posix" and stat.S_IMODE(path.stat().st_mode) & 0o077:
        raise ValueError("The private environment file must have mode 0600 or stricter.")
    values = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, separator, raw = line.partition("=")
        if not separator or not re.fullmatch(r"TENDERGUARD_[A-Z_]+", key):
            raise ValueError("Use the private file generated by configure_env.py.")
        parsed = shlex.split(raw, comments=False)
        if len(parsed) != 1 or key in values:
            raise ValueError("Invalid or duplicate private environment value.")
        values[key] = parsed[0]
    validate_domain(values.get("TENDERGUARD_DOMAIN", ""))
    if len(values.get("TENDERGUARD_API_KEY", "")) < 32:
        raise ValueError("A private API key of at least 32 characters is required.")
    if len(values.get("TENDERGUARD_DASHBOARD_PASSWORD", "")) < 16:
        raise ValueError("A private dashboard password of at least 16 characters is required.")
    if values.get("TENDERGUARD_OLLAMA_MODEL") != "qwen3:1.7b":
        raise ValueError("This verified demo procedure requires qwen3:1.7b.")


def instance_identity() -> dict:
    # Never send IMDS requests through a configured proxy or print the session token.
    opener = build_opener(ProxyHandler({}))
    with opener.open(
        Request(
            "http://169.254.169.254/latest/api/token",
            method="PUT",
            headers={"X-aws-ec2-metadata-token-ttl-seconds": "60"},
        ),
        timeout=5,
    ) as response:
        token = response.read().decode()
    with opener.open(
        Request(
            "http://169.254.169.254/latest/dynamic/instance-identity/document",
            headers={"X-aws-ec2-metadata-token": token},
        ),
        timeout=5,
    ) as response:
        return json.load(response)


def validate_host(expected: str, identity: dict, *, now: datetime | None = None) -> None:
    if not re.fullmatch(r"i-[a-f0-9]{8,17}", expected) or expected == PROTECTED_INSTANCE:
        raise ValueError("Only the newly approved dedicated EC2 instance may be targeted.")
    if identity.get("region") != "eu-north-1":
        raise ValueError("This deployment is prepared for eu-north-1 only.")
    deadline = shutdown_deadline(identity, expected, now=now)
    if deadline <= (now or datetime.now(UTC)):
        raise ValueError("The eight-hour window from EC2 launch has expired.")
    run_command(["systemctl", "is-active", "--quiet", "tenderguard-demo-stop.timer"])
    run_command(["systemctl", "is-enabled", "--quiet", "tenderguard-demo-stop.timer"])
    timer = run_command(["systemctl", "cat", "tenderguard-demo-stop.timer"])
    expected_calendar = deadline.strftime("OnCalendar=%Y-%m-%d %H:%M:%S UTC")
    if expected_calendar not in timer.splitlines() or "Persistent=true" not in timer.splitlines():
        raise ValueError("The persistent shutdown timer does not match launch plus eight hours.")
    service = run_command(["systemctl", "cat", "tenderguard-demo-stop.service"])
    if "ExecStart=/usr/sbin/shutdown -h now" not in service.splitlines():
        raise ValueError("The shutdown timer has an unexpected service action.")


def deploy(env_file: Path, expected: str | None, *, check_only: bool = False) -> None:
    env_file = env_file.resolve(strict=True)
    validate_environment(env_file)
    compose = [
        "docker",
        "compose",
        "--env-file",
        str(env_file),
        "-f",
        str(ROOT / "deploy/aws/compose.aws.yaml"),
    ]
    run_command([*compose, "config", "--quiet"])
    if check_only:
        print("Private environment and production Compose configuration passed validation.")
        return
    if expected is None or expected == PROTECTED_INSTANCE:
        raise ValueError("Supply the newly approved instance ID; protected hosts are refused.")
    identity = instance_identity()
    operations = [
        (["build"], "Building application image", 1800),
        (["up", "-d", "--wait", "--wait-timeout", "120", "ollama"], "Starting private Ollama", 600),
        (
            ["exec", "-T", "ollama", "ollama", "pull", "qwen3:1.7b"],
            "Preparing the Qwen model",
            1200,
        ),
        (["up", "-d", "--wait", "--wait-timeout", "180"], "Starting the HTTPS application", 600),
    ]
    for arguments, message, timeout in operations:
        # Recheck before every mutation; a slow build must not extend the launch window.
        validate_host(expected, identity)
        print(message, flush=True)
        run_command([*compose, *arguments], timeout=timeout)
    validate_host(expected, identity)
    print("Containers are healthy. Run verify_cloud against the public HTTPS hostname.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--env-file", type=Path, default=ROOT / "deploy/aws/.env")
    parser.add_argument("--expected-instance-id")
    parser.add_argument("--check-only", action="store_true")
    args = parser.parse_args()
    try:
        deploy(args.env_file, args.expected_instance_id, check_only=args.check_only)
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as exc:
        parser.exit(1, f"Deployment stopped: {exc}\n")


if __name__ == "__main__":
    main()
